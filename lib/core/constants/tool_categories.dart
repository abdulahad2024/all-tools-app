  static CategoryModel getCategoryById(String id) {
    return categories.firstWhere(
      (c) => c.id == id,
      orElse: () => categories.first,
    );
  }

  static ToolModel getToolById(String id) {
    return tools.firstWhere(
      (t) => t.id == id,
      orElse: () => tools.first,
    );
  }

  static List<ToolModel> getToolsForCategory(String categoryId) {
    return tools.where((t) => t.categoryId == categoryId).toList();
  }
